__attribute__((noinline)) static u64 quotient(u64 a, u64 b) { return a / b; }
__attribute__((noinline)) static u64 remainder(u64 a, u64 b) { return a % b; }
void test_body(void) {
    unsigned badq = 0, badr = 0, badnull = 0, patterns = 0, guards = 0;
    unsigned registers = 0, first = ~0u;
    u64 firstq = 0, firstr = 0;
    for (unsigned i = 0; i < sizeof(cases) / sizeof(*cases); ++i) {
        struct { volatile unsigned before; u64 r; volatile unsigned after; } result;
        result.before = 0x13579bdf; result.r = 0xfeedfacecafebeefULL;
        result.after = 0x2468ace0;
        u64 q = helper_probe(cases[i].a, cases[i].b, &result.r);
        registers |= helper_bad_registers();
        if (q != cases[i].q) ++badq;
        if (result.r != cases[i].r) ++badr;
        if ((q != cases[i].q || result.r != cases[i].r) && first == ~0u) {
            first = i; firstq = q; firstr = result.r;
        }
        if (result.before != 0x13579bdf || result.after != 0x2468ace0) ++guards;
        if (helper_probe(cases[i].a, cases[i].b, 0) != cases[i].q) ++badnull;
        registers |= helper_bad_registers();
        if (quotient(cases[i].a, cases[i].b) != cases[i].q ||
            remainder(cases[i].a, cases[i].b) != cases[i].r) ++patterns;
    }
    observe("udiv.cases", sizeof(cases) / sizeof(*cases));
    observe("udiv.bad_quotient", badq); observe("udiv.bad_remainder", badr);
    observe("udiv.bad_null", badnull); observe("udiv.bad_patterns", patterns);
    observe("udiv.bad_guards", guards); observe("udiv.first_bad", first);
    OBSERVE64("udiv.first_quotient", firstq); OBSERVE64("udiv.first_remainder", firstr);
    observe("abi.bad_registers", registers);
}
